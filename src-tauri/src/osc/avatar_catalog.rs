    #[test]
    fn suggests_the_parameter_that_was_probably_meant() {
        let a = sps3_avatar();
        let suggestion = |name: &str| suggest(&a, &addr(name));
        // Different capitals
        assert_eq!(suggestion("boop"), Some(addr("Boop")));
        assert_eq!(suggestion("TAILWAG"), Some(addr("TailWag")));
        // A letter or two off
        assert_eq!(suggestion("TailWagg"), Some(addr("TailWag")));
        assert_eq!(suggestion("Tailwg"), Some(addr("TailWag")));
        // Too short to guess, or too far off
        assert_eq!(suggestion("Bop"), None);
        assert_eq!(suggestion("Something"), None);
        // Ints aren't suggested, as they can't be used
        assert_eq!(suggestion("outfit"), None);
    }

