/*
 * The current avatar's parameters, read from VRChat's OSCQuery server, for
 * setup help: the parameter picker and the warnings in a feature's settings.
 *
 * One task runs for the life of the app (also while VibeCheck is off, since
 * setup usually happens first). It only reads from VRChat: an mDNS lookup
 * and HTTP requests. It doesn't advertise anything or open an OSC port.
 *
 * - While VRChat isn't found, it looks again every LOOKUP_EVERY.
 * - Once found, it asks for `/avatar/change` every POLL_EVERY (one small
 *   request) and reads the full `/avatar/parameters` tree when the avatar
 *   changes, then again a few times while VRChat finishes loading it.
 * - `refresh` reads everything again straight away (the Refresh button).
 *
 * It also tells whether VRChat is running (`presence`), which plain OSC
 * can't: VRChat just stops sending. VRChat counts as gone after
 * MISSES_UNTIL_GONE failed requests in a row (about 6 to 9 seconds), so one
 * slow answer doesn't count. The listening session turns changes into
 * connection events (see runtime/presence.rs).
 *
 * The avatar's id is only used to notice changes. It isn't shown or logged.
 *
 * `check_feature` compares one feature's settings with the avatar, so every
 * rule lives here, with tests, and the frontend only shows the result.
 */

