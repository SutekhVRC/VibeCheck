#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ParamKind {
    Float,
    Bool,
    Int,
    /// Anything else VRChat reports (it shouldn't, for avatar parameters).
    Other,
}

impl ParamKind {
    fn from_type_tag(tag: Option<&str>) -> Self {
        match tag {
            Some("f") => Self::Float,
            Some("T") | Some("F") => Self::Bool,
            Some("i") => Self::Int,
            _ => Self::Other,
        }
    }

    /// Whether VibeCheck can use it: the OSC input reads floats and bools.
    pub fn usable(self) -> bool {
        matches!(self, Self::Float | Self::Bool)
    }
}

/// What a parameter is for, so the picker can put the avatar's own first.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ParamGroup {
    /// Made by the avatar's creator (contacts, toggles...)
    Own,
    Sps,
    Tps,
    /// Generated by VRCFury (`VF12_...`). Built partly from GameObject names
    /// and component ids, so they can change when the avatar is rebuilt.
    VrcFury,
    /// Given to every avatar by VRChat
    BuiltIn,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AvatarParam {
    /// The full OSC address, e.g. `/avatar/parameters/Boop`.
    pub address: String,
    pub kind: ParamKind,
    pub group: ParamGroup,
}

/// One avatar's parameters, and what they tell about it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Avatar {
    /// Sorted by address.
    pub params: Vec<AvatarParam>,
    pub zones: Vec<ZoneInfo>,
    pub tps: bool,
    index: HashMap<String, usize>,
}

impl Avatar {
    /// Reads the tree under `/avatar/parameters`.
    pub fn from_tree(tree: &OSCQueryNode) -> Self {
        let mut params: Vec<AvatarParam> = tree
            .leaves()
            .into_iter()
            .filter_map(|leaf| {
                let name = leaf.full_path.strip_prefix(PARAMS_PREFIX)?;
                Some(AvatarParam {
                    address: leaf.full_path.clone(),
                    kind: ParamKind::from_type_tag(leaf.type_tag()),
                    group: group_of(name),
                })
            })
            .collect();
        params.sort_by(|a, b| a.address.cmp(&b.address));
        params.dedup_by(|a, b| a.address == b.address);
        Self::from_params(params)
    }

    fn from_params(params: Vec<AvatarParam>) -> Self {
        let names = params
            .iter()
            .filter_map(|p| p.address.strip_prefix(PARAMS_PREFIX));
        let zones = sps::zones(names);
        let tps = params.iter().any(|p| p.group == ParamGroup::Tps);
        let index = params
            .iter()
            .enumerate()
            .map(|(i, p)| (p.address.clone(), i))
            .collect();
        Self {
            params,
            zones,
            tps,
            index,
        }
    }

    pub fn param(&self, address: &str) -> Option<&AvatarParam> {
        self.index.get(address).map(|&i| &self.params[i])
    }

    pub fn has_sps(&self) -> bool {
        !self.zones.is_empty()
    }
}

fn group_of(name: &str) -> ParamGroup {
    if name.starts_with("OGB/") || name.starts_with("VFH/") {
        ParamGroup::Sps
    } else if tps::is_tps_parameter(name) {
        ParamGroup::Tps
    } else if is_vrcfury_generated(name) {
        ParamGroup::VrcFury
    } else if BUILT_IN.contains(&name) {
        ParamGroup::BuiltIn
    } else {
        ParamGroup::Own
    }
}

/// VRCFury's generated names: `VF` and an optional number, then `_`.
fn is_vrcfury_generated(name: &str) -> bool {
    name.strip_prefix("VF")
        .map(|rest| rest.trim_start_matches(|c: char| c.is_ascii_digit()))
        .is_some_and(|rest| rest.starts_with('_'))
}

/// What a feature's settings miss on the current avatar.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct FeatureCheck {
    /// Parameters the avatar doesn't have, with a likely intended one.
    pub missing: Vec<MissingParam>,
    /// Parameters the avatar has, but VibeCheck can't use (ints).
    pub unusable: Vec<AvatarParam>,
    /// Input filter tags that match none of the avatar's SPS zones.
    pub unmatched_tags: Vec<String>,
    /// The Processor's system, if the avatar has none of it.
    pub system_missing: Option<PenetrationSystemType>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MissingParam {
    pub address: String,
    /// A parameter the avatar does have that was probably meant: the same
    /// name in different capitals, or one or two letters off.
    pub suggestion: Option<String>,
}

/// Compares one feature's settings with `avatar`.
pub fn check_feature(
    avatar: &Avatar,
    parameters: &[String],
    system: PenetrationSystemType,
    tags: &[String],
) -> FeatureCheck {
    let mut check = FeatureCheck::default();

    for address in parameters {
        match avatar.param(address) {
            Some(param) if !param.kind.usable() => check.unusable.push(param.clone()),
            Some(_) => {}
            None => check.missing.push(MissingParam {
                address: address.clone(),
                suggestion: suggest(avatar, address),
            }),
        }
    }

    match system {
        PenetrationSystemType::Sps if !avatar.has_sps() => {
            check.system_missing = Some(PenetrationSystemType::Sps);
        }
        PenetrationSystemType::Sps => {
            check.unmatched_tags = tags
                .iter()
                .filter(|tag| {
                    !avatar
                        .zones
                        .iter()
                        .any(|zone| sps::tag_matches_zone(tag, &zone.name))
                })
                .cloned()
                .collect();
        }
        PenetrationSystemType::Tps if !avatar.tps => {
            check.system_missing = Some(PenetrationSystemType::Tps);
        }
        _ => {}
    }

    check
}

/// The avatar's usable parameter `address` most likely meant: the same
/// address ignoring capitals, or else the only one within a couple of
/// letters of it.
fn suggest(avatar: &Avatar, address: &str) -> Option<String> {
    let usable = || avatar.params.iter().filter(|p| p.kind.usable());
    if let Some(p) = usable().find(|p| p.address.eq_ignore_ascii_case(address)) {
        return Some(p.address.clone());
    }

    let name = address.strip_prefix(PARAMS_PREFIX)?;
    // Short names are too easy to match by accident
    let max = match name.chars().count() {
        0..=3 => return None,
        4..=7 => 1,
        _ => 2,
    };
    let mut best: Option<(usize, &AvatarParam)> = None;
    let mut tied = false;
    for p in usable() {
        let Some(other) = p.address.strip_prefix(PARAMS_PREFIX) else {
            continue;
        };
        let distance = edit_distance(&name.to_lowercase(), &other.to_lowercase());
        if distance > max {
            continue;
        }
        match best {
            Some((d, _)) if distance > d => {}
            Some((d, _)) if distance == d => tied = true,
            _ => {
                best = Some((distance, p));
                tied = false;
            }
        }
    }
    match best {
        Some((_, p)) if !tied => Some(p.address.clone()),
        _ => None,
    }
}

/// Levenshtein distance, by characters.
fn edit_distance(a: &str, b: &str) -> usize {
    let a: Vec<char> = a.chars().collect();
    let b: Vec<char> = b.chars().collect();
    let mut row: Vec<usize> = (0..=b.len()).collect();
    for (i, ca) in a.iter().enumerate() {
        let mut previous = row[0];
        row[0] = i + 1;
        for (j, cb) in b.iter().enumerate() {
            let substitution = previous + usize::from(ca != cb);
            previous = row[j + 1];
            row[j + 1] = substitution.min(row[j] + 1).min(row[j + 1] + 1);
        }
    }
    row[b.len()]
}

/// What the catalog knows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CatalogState {
    /// The first look for VRChat hasn't finished yet.
    Looking,
    /// VRChat's OSCQuery server isn't found (VRChat closed, or OSC off).
    Searching,
    /// VRChat is found; reading the avatar.
    Reading,
    Ready(Arc<Avatar>),
}

/// Runs the catalog's task. Cheap to clone; clones share it.
#[derive(Clone)]
pub struct AvatarCatalog {
    state: Arc<Mutex<CatalogState>>,
    endpoint: Arc<Mutex<Option<Endpoint>>>,
    refresh: Arc<Notify>,
    task: Arc<Mutex<Option<JoinHandle<()>>>>,
    present: Arc<watch::Sender<bool>>,
}

/// Whether VRChat is running, with the grace period described at the top.
struct Presence {
    misses: u8,
}

impl Presence {
    /// VRChat answered: it's running.
    fn answered(&mut self, present: &watch::Sender<bool>) {
        self.misses = 0;
        present.send_if_modified(|p| !std::mem::replace(p, true));
    }

    /// A request failed, or VRChat wasn't found.
    fn missed(&mut self, present: &watch::Sender<bool>) {
        self.misses = self.misses.saturating_add(1);
        if self.misses >= MISSES_UNTIL_GONE {
            present.send_if_modified(|p| std::mem::replace(p, false));
        }
    }
}

impl Default for AvatarCatalog {
    fn default() -> Self {
        Self {
            state: Arc::new(Mutex::new(CatalogState::Looking)),
            endpoint: Arc::default(),
            refresh: Arc::default(),
            task: Arc::default(),
            present: Arc::new(watch::channel(false).0),
        }
    }
}

impl AvatarCatalog {
    /// Starts the task on `runtime` (once). `on_change` is called whenever
    /// the state changes.
    pub fn start(
        &self,
        runtime: &tokio::runtime::Handle,
        on_change: impl Fn(&CatalogState) + Send + Sync + 'static,
    ) {
        let mut task = self.task.lock();
        if task.is_some() {
            return;
        }
        *task = Some(runtime.spawn(run(self.clone(), Box::new(on_change))));
    }

    pub fn state(&self) -> CatalogState {
        self.state.lock().clone()
    }

    /// The current avatar, once read.
    pub fn avatar(&self) -> Option<Arc<Avatar>> {
        match &*self.state.lock() {
            CatalogState::Ready(avatar) => Some(avatar.clone()),
            _ => None,
        }
    }

    /// VRChat's OSCQuery server, while it's found.
    pub fn vrchat(&self) -> Option<Endpoint> {
        self.endpoint.lock().clone()
    }

    /// Whether VRChat is running (false until it's first found), and every
    /// change to that.
    pub fn presence(&self) -> watch::Receiver<bool> {
        self.present.subscribe()
    }

    /// Reads the avatar again now.
    pub fn refresh(&self) {
        self.refresh.notify_one();
    }

    fn set(&self, new: CatalogState, on_change: &OnChange) {
        let mut state = self.state.lock();
        if *state != new {
            *state = new.clone();
            drop(state);
            on_change(&new);
        }
    }
}

type OnChange = Box<dyn Fn(&CatalogState) + Send + Sync>;

async fn run(catalog: AvatarCatalog, on_change: OnChange) {
    let mut avatar_id: Option<String> = None;
    let mut rereads: Vec<Instant> = Vec::new();
    let mut presence = Presence { misses: 0 };
    loop {
        // Find VRChat
        let Some(endpoint) = catalog.vrchat() else {
            match discovery::find_vrchat(TIMEOUT).await {
                Ok(Some(found)) => {
                    info!("Avatar catalog: found VRChat's OSCQuery server");
                    presence.answered(&catalog.present);
                    *catalog.endpoint.lock() = Some(found);
                    avatar_id = None;
                    catalog.set(CatalogState::Reading, &on_change);
                }
                _ => {
                    presence.missed(&catalog.present);
                    catalog.set(CatalogState::Searching, &on_change);
                    wait(&catalog.refresh, Instant::now() + LOOKUP_EVERY).await;
                }
            }
            continue;
        };

        // Which avatar is loaded? Failing means VRChat went away
        let current = match discovery::node(&endpoint, AVATAR_CHANGE_PATH, TIMEOUT).await {
            Ok(node) => {
                presence.answered(&catalog.present);
                avatar_id_of(&node)
            }
            Err(e) => {
                debug!("Avatar catalog: VRChat stopped answering: {}", e);
                presence.missed(&catalog.present);
                *catalog.endpoint.lock() = None;
                catalog.set(CatalogState::Searching, &on_change);
                continue;
            }
        };

        let now = Instant::now();
        let changed = current != avatar_id;
        if changed {
            avatar_id = current;
            catalog.set(CatalogState::Reading, &on_change);
            rereads = REREAD_AFTER_CHANGE.iter().map(|d| now + *d).collect();
        }
        let reread_due = rereads.first().is_some_and(|at| *at <= now);
        if reread_due {
            rereads.remove(0);
        }
        if changed || reread_due {
            read_parameters(&catalog, &endpoint, &on_change).await;
        }

        let next_poll = Instant::now() + POLL_EVERY;
        let next = rereads.first().map_or(next_poll, |at| (*at).min(next_poll));
        if wait(&catalog.refresh, next).await {
            // Refresh: read again now, and treat it as a fresh avatar
            avatar_id = None;
        }
    }
}

/// Waits until `until`, or until a refresh is asked for (returns true).
async fn wait(refresh: &Notify, until: Instant) -> bool {
    tokio::select! {
        _ = sleep_until(until) => false,
        _ = refresh.notified() => true,
    }
}

async fn read_parameters(catalog: &AvatarCatalog, endpoint: &Endpoint, on_change: &OnChange) {
    match discovery::node(endpoint, PARAMETERS_PATH, TIMEOUT).await {
        Ok(tree) => {
            let avatar = Avatar::from_tree(&tree);
            debug!("Avatar catalog: {} parameters", avatar.params.len());
            let same =
                matches!(&*catalog.state.lock(), CatalogState::Ready(old) if **old == avatar);
            if !same {
                catalog.set(CatalogState::Ready(Arc::new(avatar)), on_change);
            }
        }
        // Still loading, or VRChat went away: the next poll finds out
        Err(e) => debug!("Avatar catalog: couldn't read the parameters: {}", e),
    }
}

fn avatar_id_of(node: &OSCQueryNode) -> Option<String> {
    match node.value()?.first()? {
        OSCQueryValue::STRING(id) => Some(id.clone()),
        _ => None,
    }
}

