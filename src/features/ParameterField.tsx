import {
  Popover,
  PopoverAnchor,
  PopoverContent,
} from "@/components/ui/popover";
import { useAvatarCatalog } from "@/context/AvatarCatalog";
import { OSC } from "@/data/constants";
import { cn } from "@/lib/utils";
import type { FeAvatarParameter } from "@bindings/FeAvatarParameter";
import type { FeParamGroup } from "@bindings/FeParamGroup";
import type { FeParamKind } from "@bindings/FeParamKind";
import { KeyboardEvent, useEffect, useMemo, useRef, useState } from "react";

/*
 * A feature parameter's name: free text, with a list of the current
 * avatar's parameters (from VRChat's OSCQuery) to pick from. Free typing
 * always works: the avatar may not be loaded, or the toy may be set up for
 * another avatar.
 */

const GROUPS: { group: FeParamGroup; label: string }[] = [
  { group: "Own", label: "Your avatar" },
  { group: "Sps", label: "SPS" },
  { group: "Tps", label: "TPS" },
  { group: "VrcFury", label: "Generated by VRCFury" },
  { group: "BuiltIn", label: "VRChat built-in" },
];

/** Most items shown per group, so a huge avatar stays quick to scroll */
const MAX_PER_GROUP = 100;

/** A new parameter's placeholder name, e.g. "param-0" */
const PLACEHOLDER = /^param-\d+$/;

const KIND_LABEL: Record<FeParamKind, string> = {
  Float: "float",
  Bool: "bool",
  Int: "int",
  Other: "other",
};

export function parameterName(address: string) {
  return address.startsWith(OSC.PARAM_PREFIX)
    ? address.slice(OSC.PARAM_PREFIX.length)
    : address;
}

export function isPlaceholder(address: string) {
  return PLACEHOLDER.test(parameterName(address));
}

export function usable(kind: FeParamKind) {
  return kind === "Float" || kind === "Bool";
}

type Section = {
  label: string;
  items: FeAvatarParameter[];
  /** Matches left out past MAX_PER_GROUP */
  more: number;
};

/**
 * The parameters to list for `query`: with no query, the avatar's own
 * parameters; otherwise every group, best matches first (the whole name,
 * then the start of it, then anywhere in it; capitals ignored).
 */
function search(parameters: FeAvatarParameter[], query: string): Section[] {
  const q = query.trim().toLowerCase();
  const rank = (p: FeAvatarParameter) => {
    const name = parameterName(p.address).toLowerCase();
    if (!q) return 0;
    if (name === q) return 0;
    if (name.startsWith(q)) return 1;
    if (name.includes(q)) return 2;
    return -1;
  };
  return GROUPS.filter(({ group }) => q || group === "Own")
    .map(({ group, label }) => {
      const matches = parameters
        .filter((p) => p.group === group && rank(p) >= 0)
        .sort((a, b) => rank(a) - rank(b));
      return {
        label,
        items: matches.slice(0, MAX_PER_GROUP),
        more: Math.max(0, matches.length - MAX_PER_GROUP),
      };
    })
    .filter((section) => section.items.length > 0);
}

export default function ParameterField({
  value,
  usedElsewhere,
  autoFocus,
  onType,
  onPick,
  onFocusChange,
}: {
  /** The full address, e.g. /avatar/parameters/Boop */
  value: string;
  /** Addresses this feature's other parameters already use */
  usedElsewhere: string[];
  autoFocus?: boolean;
  /** Typed text (just the name, without the prefix) */
  onType: (name: string) => void;
  /** A parameter picked from the list (its full address) */
  onPick: (address: string) => void;
  onFocusChange?: (focused: boolean) => void;
}) {
  const { catalog } = useAvatarCatalog();
  const inputRef = useRef<HTMLInputElement>(null);
  const listRef = useRef<HTMLDivElement>(null);
  const [focused, setFocused] = useState(false);
  const [open, setOpen] = useState(false);
  const [highlight, setHighlight] = useState(0);

  const name = parameterName(value);
  // A placeholder name isn't a search: show the avatar's parameters
  const query = PLACEHOLDER.test(name) ? "" : name;
  const ready = catalog.status === "Ready";

  const sections = useMemo(
    () => (ready ? search(catalog.parameters, query) : []),
    [ready, catalog.parameters, query],
  );
  const pickable = useMemo(
    () => sections.flatMap((s) => s.items).filter((p) => usable(p.kind)),
    [sections],
  );
  const otherGroups = useMemo(() => {
    if (query || !ready) return [];
    return GROUPS.filter(({ group }) => group !== "Own")
      .map(({ group, label }) => ({
        label,
        count: catalog.parameters.filter((p) => p.group === group).length,
      }))
      .filter((g) => g.count > 0);
  }, [query, ready, catalog.parameters]);

  useEffect(() => {
    if (autoFocus) {
      inputRef.current?.focus();
      inputRef.current?.select();
    }
  }, [autoFocus]);

  // Keep the highlighted item in view, and in range as the list changes
  useEffect(() => {
    if (highlight >= pickable.length) setHighlight(0);
    const item = listRef.current?.querySelector('[data-highlighted="true"]');
    item?.scrollIntoView({ block: "nearest" });
  }, [highlight, pickable.length]);

  function pick(address: string) {
    onPick(address);
    setOpen(false);
  }

  function onKeyDown(e: KeyboardEvent<HTMLInputElement>) {
    if (!open && (e.key === "ArrowDown" || e.key === "ArrowUp")) {
      setOpen(true);
      e.preventDefault();
      return;
    }
    if (!open || pickable.length === 0) return;
    if (e.key === "ArrowDown") {
      setHighlight((h) => (h + 1) % pickable.length);
      e.preventDefault();
    } else if (e.key === "ArrowUp") {
      setHighlight((h) => (h - 1 + pickable.length) % pickable.length);
      e.preventDefault();
    } else if (e.key === "Enter") {
      pick(pickable[highlight].address);
      e.preventDefault();
    } else if (e.key === "Escape") {
      setOpen(false);
      e.preventDefault();
    }
  }

  const showList = open && focused && ready;

  return (
    <Popover open={showList}>
      <PopoverAnchor asChild>
        <div className="theme-input flex min-w-0 items-center focus-within:border-theme-primary focus-within:ring-2 focus-within:ring-theme-primary/30">
          <span className="shrink-0 select-none text-xs text-theme-muted">
            {OSC.PARAM_PREFIX}
          </span>
          <input
            ref={inputRef}
            className="min-w-0 flex-1 bg-transparent outline-none"
            name="osc_parameter"
            aria-label="OSC parameter name"
            role="combobox"
            aria-expanded={showList}
            aria-autocomplete="list"
            autoComplete="off"
            spellCheck={false}
            value={name}
            onChange={(e) => {
              onType(e.target.value);
              setOpen(true);
              setHighlight(0);
            }}
            onFocus={(e) => {
              setFocused(true);
              setOpen(true);
              onFocusChange?.(true);
              if (PLACEHOLDER.test(e.target.value)) e.target.select();
            }}
            onBlur={() => {
              setFocused(false);
              setOpen(false);
              onFocusChange?.(false);
            }}
            onKeyDown={onKeyDown}
          />
        </div>
      </PopoverAnchor>
      <PopoverContent
        align="start"
        // Focus stays in the text field while the list is open
        onOpenAutoFocus={(e) => e.preventDefault()}
        onCloseAutoFocus={(e) => e.preventDefault()}
        className="w-[--radix-popover-trigger-width] min-w-[16rem] border-theme-border bg-theme-raised p-0 text-theme-text"
      >
        <div
          ref={listRef}
          role="listbox"
          aria-label="Your avatar's parameters"
          className="scrollbar max-h-64 overflow-y-auto py-1 text-sm"
        >
          {sections.length === 0 && (
            <div className="px-3 py-2 text-xs text-theme-muted">
              No parameter on your current avatar matches &quot;{query}&quot;.
              You can still use it: it works on any avatar that has it.
            </div>
          )}
          {sections.map((section) => (
            <div key={section.label} role="group" aria-label={section.label}>
              <div className="px-3 pb-0.5 pt-2 text-[0.7rem] font-semibold uppercase tracking-wider text-theme-muted">
                {section.label}
              </div>
              {section.items.map((p) => {
                const canUse = usable(p.kind);
                const index = canUse ? pickable.indexOf(p) : -1;
                const isHighlighted = index === highlight;
                const inUse = usedElsewhere.includes(p.address);
                return (
                  <div
                    key={p.address}
                    role="option"
                    aria-selected={isHighlighted}
                    aria-disabled={!canUse}
                    data-highlighted={isHighlighted}
                    title={
                      canUse
                        ? undefined
                        : "VibeCheck can only use float and bool parameters"
                    }
                    // Keep focus in the text field
                    onMouseDown={(e) => e.preventDefault()}
                    onMouseEnter={() => canUse && setHighlight(index)}
                    onClick={() => canUse && pick(p.address)}
                    className={cn(
                      "flex cursor-pointer items-center justify-between gap-3 px-3 py-1",
                      isHighlighted && "bg-theme-primary/15 text-theme-primary",
                      !canUse && "cursor-not-allowed opacity-50",
                    )}
                  >
                    <span className="min-w-0 truncate">
                      {parameterName(p.address)}
                    </span>
                    <span className="flex shrink-0 items-center gap-1.5 text-xs text-theme-muted">
                      {inUse && <span>in use</span>}
                      <span>{KIND_LABEL[p.kind]}</span>
                    </span>
                  </div>
                );
              })}
              {section.more > 0 && (
                <div className="px-3 py-1 text-xs text-theme-muted">
                  {section.more} more: keep typing to narrow it down
                </div>
              )}
            </div>
          ))}
          {otherGroups.length > 0 && (
            <div className="border-t border-theme-border/60 px-3 py-2 text-xs text-theme-muted">
              Type to search{" "}
              {otherGroups.map((g) => `${g.label} (${g.count})`).join(", ")}{" "}
              too.
            </div>
          )}
        </div>
      </PopoverContent>
    </Popover>
  );
}
